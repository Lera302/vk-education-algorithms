"""Слить два отсортированных массива, записав результат в первый.

В arr1 заранее есть len(arr2) свободных ячеек в конце, заполненных нулями.
Полезная часть arr1 и весь arr2 отсортированы по неубыванию.
Массивы должны быть разными объектами. arr2 не изменяется.
Заполняем arr1 с конца, чтобы не затереть его непрочитанные элементы.
Время: O(n + m), где n и m — числа полезных элементов.
Дополнительная память: O(1).
"""


def merge_in_place(arr1, arr2):
    i = len(arr1) - len(arr2) - 1
    j = len(arr2) - 1
    write = len(arr1) - 1

    while j >= 0:
        if i >= 0 and arr1[i] > arr2[j]:
            arr1[write] = arr1[i]
            i -= 1
        else:
            arr1[write] = arr2[j]
            j -= 1
        write -= 1

    return arr1


if __name__ == "__main__":
    first = [1, 3, 5, 0, 0, 0]
    second = [2, 4, 6]
    print(merge_in_place(first, second))  # [1, 2, 3, 4, 5, 6]
